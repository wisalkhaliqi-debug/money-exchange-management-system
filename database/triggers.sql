-- 1. Customer Date Trigger
CREATE OR REPLACE TRIGGER TRG_CUSTOMER_DATE
BEFORE INSERT ON CUSTOMERS
FOR EACH ROW
BEGIN
    IF :NEW.CREATEDAT IS NULL THEN
        :NEW.CREATEDAT := SYSDATE;
    END IF;
END;
/

-- 2. Transaction Total Trigger
CREATE OR REPLACE TRIGGER TRG_TRANSACTION_TOTAL
BEFORE INSERT OR UPDATE OF AMOUNT, RATE
ON TRANSACTIONS
FOR EACH ROW
BEGIN
    :NEW.TOTALAMOUNT := :NEW.AMOUNT * :NEW.RATE;
END;
/

-- 3. Cash Balance Closing Trigger
CREATE OR REPLACE TRIGGER TRG_CASHBALANCE_CLOSING
BEFORE INSERT OR UPDATE OF
    OPENINGBALANCE,
    TOTALIN,
    TOTALOUT
ON CASHBALANCE
FOR EACH ROW
BEGIN
    :NEW.CLOSINGBALANCE :=
        NVL(:NEW.OPENINGBALANCE, 0)
        + NVL(:NEW.TOTALIN, 0)
        - NVL(:NEW.TOTALOUT, 0);
END;
/
