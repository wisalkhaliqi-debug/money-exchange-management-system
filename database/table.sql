-- 1. USERS TABLE
CREATE TABLE Users (
    UserID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Username VARCHAR2(50) NOT NULL,
    Password VARCHAR2(255) NOT NULL,
    FullName VARCHAR2(100) NOT NULL,
    Role VARCHAR2(20) NOT NULL,
    Status NUMBER(1) DEFAULT 1 NOT NULL,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_Users PRIMARY KEY (UserID),
    CONSTRAINT UQ_Users_Username UNIQUE (Username),
    CONSTRAINT CK_Users_Status CHECK (Status IN (0,1))
);


-- 2. CUSTOMERS TABLE
CREATE TABLE Customers (
    CustomerID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Name VARCHAR2(100) NOT NULL,
    FatherName VARCHAR2(100),
    Phone VARCHAR2(30),
    Address VARCHAR2(255),
    IDNumber VARCHAR2(50),
    Status VARCHAR2(20) DEFAULT 'Active',
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_Customers PRIMARY KEY (CustomerID)
);


-- 3. CURRENCIES TABLE
CREATE TABLE Currencies (
    CurrencyID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Name VARCHAR2(50) NOT NULL,
    Symbol VARCHAR2(10),
    BuyRate NUMBER(18,4) DEFAULT 0,
    SellRate NUMBER(18,4) DEFAULT 0,
    Status VARCHAR2(20) DEFAULT 'Active',
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_Currencies PRIMARY KEY (CurrencyID),
    CONSTRAINT UQ_Currencies_Name UNIQUE (Name),
    CONSTRAINT CK_Currencies_BuyRate CHECK (BuyRate >= 0),
    CONSTRAINT CK_Currencies_SellRate CHECK (SellRate >= 0)
);


-- 4. EXCHANGE RATES TABLE
CREATE TABLE ExchangeRates (
    RateID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CurrencyID NUMBER NOT NULL,
    BuyRate NUMBER(18,4) NOT NULL,
    SellRate NUMBER(18,4) NOT NULL,
    RateDate DATE DEFAULT SYSDATE,
    UserID NUMBER NOT NULL,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_ExchangeRates PRIMARY KEY (RateID),

    CONSTRAINT FK_Rates_Currency
    FOREIGN KEY (CurrencyID)
    REFERENCES Currencies(CurrencyID),

    CONSTRAINT FK_Rates_User
    FOREIGN KEY (UserID)
    REFERENCES Users(UserID),

    CONSTRAINT CK_Rates_Buy CHECK (BuyRate >= 0),
    CONSTRAINT CK_Rates_Sell CHECK (SellRate >= 0)
);


-- 5. TRANSACTIONS TABLE
CREATE TABLE Transactions (
    TransactionID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CustomerID NUMBER NOT NULL,
    CurrencyID NUMBER NOT NULL,
    UserID NUMBER NOT NULL,
    TransactionType VARCHAR2(10) NOT NULL,
    Amount NUMBER(18,2) NOT NULL,
    Rate NUMBER(18,4) NOT NULL,
    TotalAmount NUMBER(18,2) NOT NULL,
    Description VARCHAR2(500),
    TransactionDate DATE DEFAULT SYSDATE,
    TransactionTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_Transactions PRIMARY KEY (TransactionID),

    CONSTRAINT FK_Transactions_Customer
    FOREIGN KEY (CustomerID)
    REFERENCES Customers(CustomerID),

    CONSTRAINT FK_Transactions_Currency
    FOREIGN KEY (CurrencyID)
    REFERENCES Currencies(CurrencyID),

    CONSTRAINT FK_Transactions_User
    FOREIGN KEY (UserID)
    REFERENCES Users(UserID),

    CONSTRAINT CK_Transactions_Type
    CHECK (TransactionType IN ('BUY','SELL')),

    CONSTRAINT CK_Transactions_Amount
    CHECK (Amount > 0),

    CONSTRAINT CK_Transactions_Rate
    CHECK (Rate > 0),

    CONSTRAINT CK_Transactions_Total
    CHECK (TotalAmount > 0)
);


-- 6. LOANS TABLE
CREATE TABLE Loans (
    LoanID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CustomerID NUMBER NOT NULL,
    CurrencyID NUMBER NOT NULL,
    Amount NUMBER(18,2) NOT NULL,
    PaidAmount NUMBER(18,2) DEFAULT 0 NOT NULL,
    RemainingAmount NUMBER(18,2) NOT NULL,
    LoanDate DATE DEFAULT SYSDATE,
    DueDate DATE,
    Status VARCHAR2(20) DEFAULT 'Unpaid',

    CONSTRAINT PK_Loans PRIMARY KEY (LoanID),

    CONSTRAINT FK_Loans_Customer
    FOREIGN KEY (CustomerID)
    REFERENCES Customers(CustomerID),

    CONSTRAINT FK_Loans_Currency
    FOREIGN KEY (CurrencyID)
    REFERENCES Currencies(CurrencyID),

    CONSTRAINT CK_Loans_Amount CHECK (Amount > 0),
    CONSTRAINT CK_Loans_Paid CHECK (PaidAmount >= 0 AND PaidAmount <= Amount),
    CONSTRAINT CK_Loans_Remaining CHECK (RemainingAmount >= 0),

    CONSTRAINT CK_Loans_Status
    CHECK (Status IN ('Unpaid','Partial','Paid'))
);


-- 7. RECEIVABLE PAYABLE TABLE
CREATE TABLE ReceivablePayable (
    RP_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CustomerID NUMBER NOT NULL,
    CurrencyID NUMBER NOT NULL,
    Type VARCHAR2(20) NOT NULL,
    Amount NUMBER(18,2) NOT NULL,
    PaidAmount NUMBER(18,2) DEFAULT 0 NOT NULL,
    RemainingAmount NUMBER(18,2) NOT NULL,
    DueDate DATE,
    Status VARCHAR2(20) DEFAULT 'Unpaid',
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_ReceivablePayable PRIMARY KEY (RP_ID),

    CONSTRAINT FK_RP_Customer
    FOREIGN KEY (CustomerID)
    REFERENCES Customers(CustomerID),

    CONSTRAINT FK_RP_Currency
    FOREIGN KEY (CurrencyID)
    REFERENCES Currencies(CurrencyID),

    CONSTRAINT CK_RP_Type
    CHECK (Type IN ('RECEIVABLE','PAYABLE')),

    CONSTRAINT CK_RP_Amount CHECK (Amount > 0),

    CONSTRAINT CK_RP_Paid
    CHECK (PaidAmount >= 0 AND PaidAmount <= Amount),

    CONSTRAINT CK_RP_Remaining
    CHECK (RemainingAmount >= 0),

    CONSTRAINT CK_RP_Status
    CHECK (Status IN ('Unpaid','Partial','Paid'))
);


-- 8. INCOME TABLE
CREATE TABLE Income (
    IncomeID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CurrencyID NUMBER NOT NULL,
    Type VARCHAR2(100) NOT NULL,
    Amount NUMBER(18,2) NOT NULL,
    Description VARCHAR2(500),
    IncomeDate DATE DEFAULT SYSDATE,
    UserID NUMBER NOT NULL,

    CONSTRAINT PK_Income PRIMARY KEY (IncomeID),

    CONSTRAINT FK_Income_Currency
    FOREIGN KEY (CurrencyID)
    REFERENCES Currencies(CurrencyID),

    CONSTRAINT FK_Income_User
    FOREIGN KEY (UserID)
    REFERENCES Users(UserID),

    CONSTRAINT CK_Income_Amount CHECK (Amount > 0)
);


-- 9. EXPENSES TABLE
CREATE TABLE Expenses (
    ExpenseID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CurrencyID NUMBER NOT NULL,
    Type VARCHAR2(100) NOT NULL,
    Amount NUMBER(18,2) NOT NULL,
    Description VARCHAR2(500),
    ExpenseDate DATE DEFAULT SYSDATE,
    UserID NUMBER NOT NULL,

    CONSTRAINT PK_Expenses PRIMARY KEY (ExpenseID),

    CONSTRAINT FK_Expenses_Currency
    FOREIGN KEY (CurrencyID)
    REFERENCES Currencies(CurrencyID),

    CONSTRAINT FK_Expenses_User
    FOREIGN KEY (UserID)
    REFERENCES Users(UserID),

    CONSTRAINT CK_Expenses_Amount CHECK (Amount > 0)
);


-- 10. CAPITAL TABLE
CREATE TABLE Capital (
    CapitalID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    OwnerName VARCHAR2(100) NOT NULL,
    CurrencyID NUMBER NOT NULL,
    Amount NUMBER(18,2) NOT NULL,
    CapitalDate DATE DEFAULT SYSDATE,
    Description VARCHAR2(500),
    UserID NUMBER NOT NULL,

    CONSTRAINT PK_Capital PRIMARY KEY (CapitalID),

    CONSTRAINT FK_Capital_Currency
    FOREIGN KEY (CurrencyID)
    REFERENCES Currencies(CurrencyID),

    CONSTRAINT FK_Capital_User
    FOREIGN KEY (UserID)
    REFERENCES Users(UserID),

    CONSTRAINT CK_Capital_Amount CHECK (Amount > 0)
);


-- 11. CASH BALANCE TABLE
CREATE TABLE CashBalance (
    CashID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CurrencyID NUMBER NOT NULL,
    OpeningBalance NUMBER(18,2) DEFAULT 0,
    TotalIn NUMBER(18,2) DEFAULT 0,
    TotalOut NUMBER(18,2) DEFAULT 0,
    ClosingBalance NUMBER(18,2) DEFAULT 0,
    BalanceDate DATE DEFAULT SYSDATE,
    UserID NUMBER NOT NULL,

    CONSTRAINT PK_CashBalance PRIMARY KEY (CashID),

    CONSTRAINT FK_Cash_Currency
    FOREIGN KEY (CurrencyID)
    REFERENCES Currencies(CurrencyID),

    CONSTRAINT FK_Cash_User
    FOREIGN KEY (UserID)
    REFERENCES Users(UserID),

    CONSTRAINT CK_Cash_Opening CHECK (OpeningBalance >= 0),
    CONSTRAINT CK_Cash_In CHECK (TotalIn >= 0),
    CONSTRAINT CK_Cash_Out CHECK (TotalOut >= 0),
    CONSTRAINT CK_Cash_Closing CHECK (ClosingBalance >= 0)
);

